public final class PowerTools extends JavaPlugin implements Listener, TabExecutor {
    private NamespacedKey itemKey;
    private NamespacedKey expiryKey;
    private NamespacedKey waterKey;
    private long lifetimeMillis;
    private int waterCapacity;
    private int maxExtraLogs;
    private boolean drillEnabled;
    private boolean axeEnabled;
    private boolean timberEnabled;
    private boolean shovelEnabled;
    private boolean bucketEnabled;
    private boolean drillSilkTouch;

    // Prevents the extra BlockBreakEvents generated by this plugin from starting
    // another 3x3/timber operation recursively.
    private final Set<UUID> processingPlayers = new HashSet<>();

    @Override
    public void onEnable() {
        itemKey = new NamespacedKey(this, "power_item");
        expiryKey = new NamespacedKey(this, "expires_at");
        waterKey = new NamespacedKey(this, "stored_water");

        saveDefaultConfig();
        loadSettings();
        getServer().getPluginManager().registerEvents(this, this);

        if (getCommand("powertools") == null) {
            getLogger().severe("Der Befehl 'powertools' fehlt in plugin.yml. Plugin wird deaktiviert.");
            getServer().getPluginManager().disablePlugin(this);
            return;
        }
        Objects.requireNonNull(getCommand("powertools")).setExecutor(this);
        Objects.requireNonNull(getCommand("powertools")).setTabCompleter(this);

        new BukkitRunnable() {
            @Override
            public void run() {
                removeExpiredItems();
            }
        }.runTaskTimer(this, 20L, 20L * 30L);

        getLogger().info("PowerTools 2.0.0 aktiviert. Enthalten: Drill, Axe, Shovel und Bucket.");
    }

    private void loadSettings() {
        reloadConfig();
        long days = Math.max(1, getConfig().getLong("lifetime-days", 5));
        lifetimeMillis = days * 24L * 60L * 60L * 1000L;
        waterCapacity = Math.max(1, getConfig().getInt("blitz-bucket.capacity", 21));
        maxExtraLogs = Math.max(1, Math.min(255, getConfig().getInt("blitz-axe.max-extra-logs", 63)));
        drillEnabled = getConfig().getBoolean("blitz-drill.enabled", true);
        axeEnabled = getConfig().getBoolean("blitz-axe.enabled", true);
        timberEnabled = getConfig().getBoolean("blitz-axe.timber-enabled", true);
        shovelEnabled = getConfig().getBoolean("blitz-shovel.enabled", true);
        bucketEnabled = getConfig().getBoolean("blitz-bucket.enabled", true);
        drillSilkTouch = getConfig().getBoolean("blitz-drill.silk-touch", true);
    }

    private ItemStack createTool(String id) {
        Material material;
        String displayName;
        List<String> lore = new ArrayList<>();

        switch (id.toLowerCase(Locale.ROOT)) {
            case "drill" -> {
                if (!drillEnabled) return null;
                material = Material.NETHERITE_PICKAXE;
                displayName = "§e§l⚡ Blitz Drill";
                lore.add("§7Baut eine Fläche von 3x3 Blöcken ab.");
            }
            case "axe" -> {
                if (!axeEnabled) return null;
                material = Material.NETHERITE_AXE;
                displayName = "§e§l⚡ Blitz Axe";
                lore.add(timberEnabled ? "§7Fällt verbundene Baumstämme." : "§7Verstärkte Axt.");
            }
            case "shovel" -> {
                if (!shovelEnabled) return null;
                material = Material.NETHERITE_SHOVEL;
                displayName = "§e§l⚡ Blitz Shovel";
                lore.add("§7Baut Erde, Sand und Kies in 3x3 ab.");
            }
            case "bucket" -> {
                if (!bucketEnabled) return null;
                material = Material.BUCKET;
                displayName = "§e§l⚡ Blitz Eimer";
                lore.add("§7Gespeichertes Wasser: §e0§7/§e" + waterCapacity);
                lore.add("§8Rechtsklick auf eine Wasserquelle: aufnehmen");
                lore.add("§8Rechtsklick auf einen Block: platzieren");
            }
            default -> {
                return null;
            }
        }

        ItemStack item = new ItemStack(material);
        ItemMeta meta = item.getItemMeta();
        if (meta == null) return null;
        meta.setDisplayName(displayName);

        if (!id.equalsIgnoreCase("bucket")) {
            meta.addEnchant(Enchantment.DIG_SPEED, 5, true);
            meta.addEnchant(Enchantment.DURABILITY, 3, true);
            meta.addEnchant(Enchantment.MENDING, 1, true);
            if (id.equalsIgnoreCase("drill") && drillSilkTouch) {
                meta.addEnchant(Enchantment.SILK_TOUCH, 1, true);
            }
        }

        int modelData = switch (id.toLowerCase(Locale.ROOT)) {
            case "drill" -> 1001;
            case "axe" -> 1002;
            case "shovel" -> 1003;
            default -> 1004;
        };
        meta.setCustomModelData(modelData);
        meta.getPersistentDataContainer().set(itemKey, PersistentDataType.STRING, id.toLowerCase(Locale.ROOT));
        long expiry = System.currentTimeMillis() + lifetimeMillis;
        meta.getPersistentDataContainer().set(expiryKey, PersistentDataType.LONG, expiry);
        if (id.equalsIgnoreCase("bucket")) {
            meta.getPersistentDataContainer().set(waterKey, PersistentDataType.INTEGER, 0);
        }
        lore.add("");
        lore.add("§8PowerTools §7• §e" + Math.max(1, lifetimeMillis / (24L * 60L * 60L * 1000L)) + " Tage gültig");
        lore.add("§7Läuft ab: §e" + new SimpleDateFormat("dd.MM.yyyy HH:mm").format(new Date(expiry)));
        meta.setLore(lore);
        item.setItemMeta(meta);
        return item;
    }

    private String getPowerId(ItemStack item) {
        if (item == null || item.getType().isAir() || !item.hasItemMeta() || itemKey == null) return null;
        return item.getItemMeta().getPersistentDataContainer().get(itemKey, PersistentDataType.STRING);
    }

    private int getStoredWater(ItemStack item) {
        if (item == null || !item.hasItemMeta()) return 0;
        return item.getItemMeta().getPersistentDataContainer().getOrDefault(waterKey, PersistentDataType.INTEGER, 0);
    }

    private void updateBucket(ItemStack item, int stored) {
        ItemMeta meta = item.getItemMeta();
        if (meta == null) return;
        int amount = Math.max(0, Math.min(waterCapacity, stored));
        meta.getPersistentDataContainer().set(waterKey, PersistentDataType.INTEGER, amount);
        List<String> lore = meta.hasLore() && meta.getLore() != null
                ? new ArrayList<>(meta.getLore()) : new ArrayList<>();
        if (!lore.isEmpty()) lore.set(0, "§7Gespeichertes Wasser: §e" + amount + "§7/§e" + waterCapacity);
        meta.setLore(lore);
        item.setItemMeta(meta);
    }

    @EventHandler(ignoreCancelled = true)
    public void onInteract(PlayerInteractEvent event) {
        if (event.getHand() != EquipmentSlot.HAND) return;
        ItemStack hand = event.getItem();
        String id = getPowerId(hand);
        if (!"bucket".equals(id) || !bucketEnabled) return;
        if (event.getAction() != Action.RIGHT_CLICK_BLOCK && event.getAction() != Action.RIGHT_CLICK_AIR) return;

        event.setCancelled(true);
        Block clicked = event.getClickedBlock();
        if (clicked == null) return;
        Player player = event.getPlayer();
        int stored = getStoredWater(hand);

        if (clicked.getType() == Material.WATER
                && clicked.getBlockData() instanceof Levelled levelled
                && levelled.getLevel() == 0) {
            if (stored >= waterCapacity) {
                player.sendMessage("§e[PowerTools] §cDein Blitz Eimer ist voll (" + waterCapacity + "/" + waterCapacity + ").");
                return;
            }
            clicked.setType(Material.AIR);
            updateBucket(hand, stored + 1);
            player.sendMessage("§e[PowerTools] §aWasser aufgenommen: §e" + (stored + 1) + "/" + waterCapacity);
            return;
        }

        if (stored <= 0) return;
        BlockFace face = event.getBlockFace();
        if (face == null) return;
        Block target = clicked.getRelative(face);
        if (target.getType().isAir() || target.isReplaceable()) {
            target.setType(Material.WATER);
            updateBucket(hand, stored - 1);
            player.sendMessage("§e[PowerTools] §aWasser platziert: §e" + (stored - 1) + "/" + waterCapacity);
        }
    }

    @EventHandler(ignoreCancelled = true)
    public void onBlockBreak(BlockBreakEvent event) {
        Player player = event.getPlayer();
        UUID playerId = player.getUniqueId();
        if (processingPlayers.contains(playerId)) return;

        ItemStack tool = player.getInventory().getItemInMainHand();
        String id = getPowerId(tool);
        if (id == null) return;

        if (id.equals("drill") && drillEnabled) {
            processingPlayers.add(playerId);
            try {
                breakThreeByThree(event, tool, player, false);
            } finally {
                processingPlayers.remove(playerId);
            }
        } else if (id.equals("shovel") && shovelEnabled) {
            processingPlayers.add(playerId);
            try {
                breakThreeByThree(event, tool, player, true);
            } finally {
                processingPlayers.remove(playerId);
            }
        } else if (id.equals("axe") && axeEnabled && timberEnabled && Tag.LOGS.isTagged(event.getBlock().getType())) {
            processingPlayers.add(playerId);
            try {
                fellTree(event.getBlock(), tool, player);
            } finally {
                processingPlayers.remove(playerId);
            }
        }
    }

    private void breakThreeByThree(BlockBreakEvent mainEvent, ItemStack tool, Player player, boolean shovelMode) {
        Block center = mainEvent.getBlock();
        BlockFace facing = player.getFacing();
        for (int first = -1; first <= 1; first++) {
            for (int second = -1; second <= 1; second++) {
                if (first == 0 && second == 0) continue;
                Block extra;
                boolean lookingDown = shovelMode && player.getLocation().getPitch() > 55.0f;
                if (lookingDown) {
                    extra = center.getRelative(first, 0, second);
                } else if (facing == BlockFace.NORTH || facing == BlockFace.SOUTH) {
                    extra = center.getRelative(first, second, 0);
                } else {
                    extra = center.getRelative(0, second, first);
                }
                if (shovelMode && !isShovelBlock(extra.getType())) continue;
                if (!shovelMode && !isBreakable(extra)) continue;
                breakExtraBlock(extra, tool, player);
            }
        }
    }

    private boolean isShovelBlock(Material material) {
        return switch (material) {
            case DIRT, GRASS_BLOCK, COARSE_DIRT, ROOTED_DIRT, PODZOL, MYCELIUM,
                 MUD, CLAY, SAND, RED_SAND, GRAVEL, SNOW, SNOW_BLOCK,
                 SOUL_SAND, SOUL_SOIL, FARMLAND, DIRT_PATH, MUDDY_MANGROVE_ROOTS -> true;
            default -> false;
        };
    }

    private boolean isBreakable(Block block) {
        if (block.getType().isAir() || block.getType() == Material.BEDROCK
                || block.getType() == Material.BARRIER || block.getType() == Material.END_PORTAL
                || block.getType() == Material.END_GATEWAY || block.getType() == Material.NETHER_PORTAL
                || block.getType() == Material.COMMAND_BLOCK || block.getType() == Material.CHAIN_COMMAND_BLOCK
                || block.getType() == Material.REPEATING_COMMAND_BLOCK || block.getType() == Material.STRUCTURE_BLOCK
                || block.getType() == Material.JIGSAW) return false;
        return !(block.getState() instanceof TileState);
    }

    private void fellTree(Block start, ItemStack tool, Player player) {
        Set<Block> found = new LinkedHashSet<>();
        Queue<Block> queue = new ArrayDeque<>();
        queue.add(start);
        while (!queue.isEmpty() && found.size() < maxExtraLogs) {
            Block current = queue.poll();
            for (int x = -1; x <= 1; x++) {
                for (int y = -1; y <= 1; y++) {
                    for (int z = -1; z <= 1; z++) {
                        if (x == 0 && y == 0 && z == 0) continue;
                        Block next = current.getRelative(x, y, z);
                        if (next.equals(start) || found.contains(next) || !Tag.LOGS.isTagged(next.getType())) continue;
                        found.add(next);
                        queue.add(next);
                        if (found.size() >= maxExtraLogs) break;
                    }
                    if (found.size() >= maxExtraLogs) break;
                }
                if (found.size() >= maxExtraLogs) break;
            }
        }
        for (Block block : found) breakExtraBlock(block, tool, player);
    }

    private void breakExtraBlock(Block block, ItemStack tool, Player player) {
        if (!isBreakable(block)) return;
        BlockBreakEvent extraEvent = new BlockBreakEvent(block, player);
        Bukkit.getPluginManager().callEvent(extraEvent);
        if (extraEvent.isCancelled()) return;

        List<ItemStack> drops = extraEvent.isDropItems()
                ? new ArrayList<>(block.getDrops(tool, player)) : Collections.emptyList();
        block.setType(Material.AIR, false);
        for (ItemStack drop : drops) {
            if (drop != null && drop.getType() != Material.AIR) {
                block.getWorld().dropItemNaturally(block.getLocation(), drop);
            }
        }
    }

    @EventHandler
    public void onJoin(PlayerJoinEvent event) {
        removeExpiredFrom(event.getPlayer().getInventory(), System.currentTimeMillis());
        removeExpiredFrom(event.getPlayer().getEnderChest(), System.currentTimeMillis());
    }

    private void removeExpiredItems() {
        long now = System.currentTimeMillis();
        for (Player player : Bukkit.getOnlinePlayers()) {
            removeExpiredFrom(player.getInventory(), now);
            removeExpiredFrom(player.getEnderChest(), now);
        }
        for (World world : Bukkit.getWorlds()) {
            for (Item itemEntity : world.getEntitiesByClass(Item.class)) {
                if (isExpired(itemEntity.getItemStack(), now)) itemEntity.remove();
            }
        }
    }

    private void removeExpiredFrom(Inventory inventory, long now) {
        for (int slot = 0; slot < inventory.getSize(); slot++) {
            ItemStack item = inventory.getItem(slot);
            if (isExpired(item, now)) inventory.setItem(slot, null);
        }
    }

    private boolean isExpired(ItemStack item, long now) {
        if (getPowerId(item) == null || !item.hasItemMeta()) return false;
        Long expiry = item.getItemMeta().getPersistentDataContainer().get(expiryKey, PersistentDataType.LONG);
        return expiry != null && expiry <= now;
    }

    @Override
    public boolean onCommand(CommandSender sender, Command command, String label, String[] args) {
        if (args.length == 1 && args[0].equalsIgnoreCase("reload")) {
            if (!sender.hasPermission("powertools.admin")) {
                sender.sendMessage("§cKeine Berechtigung.");
                return true;
            }
            loadSettings();
            sender.sendMessage("§e[PowerTools] §aConfig neu geladen.");
            return true;
        }

        if (args.length < 3 || !args[0].equalsIgnoreCase("give")) {
            sender.sendMessage("§ePowerTools §7• §f/powertools give <Spieler> <drill|axe|shovel|bucket> [Anzahl]");
            sender.sendMessage("§7Weitere Befehle: §f/powertools reload");
            return true;
        }
        if (!sender.hasPermission("powertools.admin")) {
            sender.sendMessage("§cKeine Berechtigung.");
            return true;
        }

        Player target = Bukkit.getPlayerExact(args[1]);
        if (target == null) {
            sender.sendMessage("§cSpieler ist nicht online.");
            return true;
        }

        ItemStack item = createTool(args[2]);
        if (item == null) {
            sender.sendMessage("§cUnbekanntes oder deaktiviertes Tool. Nutze drill, axe, shovel oder bucket.");
            return true;
        }

        int amount = 1;
        if (args.length >= 4) {
            try {
                amount = Math.max(1, Math.min(64, Integer.parseInt(args[3])));
            } catch (NumberFormatException ignored) {
                sender.sendMessage("§cDie Anzahl muss eine Zahl zwischen 1 und 64 sein.");
                return true;
            }
        }
        item.setAmount(amount);
        Map<Integer, ItemStack> leftovers = target.getInventory().addItem(item);
        leftovers.values().forEach(left -> target.getWorld().dropItemNaturally(target.getLocation(), left));
        sender.sendMessage("§a" + amount + "x " + args[2].toLowerCase(Locale.ROOT) + " an " + target.getName() + " gegeben.");
        target.sendMessage("§e[PowerTools] §aDu hast ein PowerTool erhalten!");
        return true;
    }

    @Override
    public List<String> onTabComplete(CommandSender sender, Command command, String alias, String[] args) {
        if (args.length == 1) return List.of("give", "reload");
        if (args.length == 2 && args[0].equalsIgnoreCase("give")) {
            return Bukkit.getOnlinePlayers().stream().map(Player::getName).toList();
        }
        if (args.length == 3 && args[0].equalsIgnoreCase("give")) {
            return List.of("drill", "axe", "shovel", "bucket");
        }
        return Collections.emptyList();
    }
}
